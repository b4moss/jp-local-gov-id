/**
 * Copy data payloads into site/public for browser demos (`url` mode),
 * and emit a browser-safe playground dataset module (avoids Node-only dataset.js).
 *
 * Demos use uncompressed `.bin` (not `.bin.br`) so browsers without
 * DecompressionStream("brotli") still work. CDN/npm continue to ship `.bin.br`.
 * Run before `nuxt dev` / `nuxt generate`.
 */
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const siteDir = join(scriptDir, "..");
const rootDir = join(siteDir, "..");
const src = join(rootDir, "packages/jp-local-gov-id-data");
const dest = join(siteDir, "public/jp-local-gov-id-data");
const playgroundDir = join(siteDir, "app/components/playground");
const generatedDatasetPath = join(playgroundDir, "generatedDataset.ts");

function copyBinTree(fromDir, toDir) {
  mkdirSync(toDir, { recursive: true });
  for (const name of readdirSync(fromDir, { withFileTypes: true })) {
    const from = join(fromDir, name.name);
    const to = join(toDir, name.name);
    if (name.isDirectory()) {
      copyBinTree(from, to);
    } else if (
      name.name.endsWith(".bin") &&
      !name.name.endsWith(".bin.br")
    ) {
      copyFileSync(from, to);
    }
  }
}

function rewriteIndexForUncompressedBins(index) {
  const paths = { ...index.paths };
  paths.prefectures = String(paths.prefectures).replace(/\.bin\.br$/u, ".bin");
  paths.municipalitiesByPrefecture = String(
    paths.municipalitiesByPrefecture,
  ).replace(/\.bin\.br$/u, ".bin");
  if (paths.searchNgrams?.twoGram?.pattern) {
    paths.searchNgrams = {
      ...paths.searchNgrams,
      twoGram: {
        ...paths.searchNgrams.twoGram,
        pattern: String(paths.searchNgrams.twoGram.pattern).replace(
          /\.bin\.br$/u,
          ".bin",
        ),
      },
      threeGram: {
        ...paths.searchNgrams.threeGram,
        pattern: String(paths.searchNgrams.threeGram.pattern).replace(
          /\.bin\.br$/u,
          ".bin",
        ),
      },
    };
  }
  return { ...index, paths };
}

rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });

const index = rewriteIndexForUncompressedBins(
  JSON.parse(readFileSync(join(src, "index.json"), "utf8")),
);
writeFileSync(join(dest, "index.json"), `${JSON.stringify(index, null, 2)}\n`);
copyFileSync(join(src, "prefectures.bin"), join(dest, "prefectures.bin"));
copyBinTree(join(src, "prefectures"), join(dest, "prefectures"));
copyBinTree(join(src, "search-ngrams"), join(dest, "search-ngrams"));

console.log(`Prepared ${dest} (uncompressed .bin for demos)`);

// Node-only dataset → static TS for Vite playground (no node:fs in the browser graph).
const dataset = await import(pathToFileURL(join(src, "dataset.js")).href);
const {
  index: datasetIndex,
  prefectures,
  municipalitiesByCode,
  searchNgramShards,
} = dataset.default ?? dataset;

const shardLiteral = Object.fromEntries(
  Object.entries(searchNgramShards).map(([key, bytes]) => [
    key,
    Array.from(bytes),
  ]),
);

const generated = `/** Auto-generated by site/scripts/prepare-data.mjs — do not edit. */
export const index = ${JSON.stringify(datasetIndex)} as const;
export const prefectures = ${JSON.stringify(prefectures)} as const;
export const municipalitiesByCode = ${JSON.stringify(municipalitiesByCode)} as const;
export const searchNgramShardArrays: Record<string, number[]> = ${JSON.stringify(shardLiteral)};
`;

writeFileSync(generatedDatasetPath, generated, "utf8");
console.log(`Wrote ${generatedDatasetPath}`);
