#!/usr/bin/env node
/**
 * Compile message catalogs:
 * - src/messages.jsonc → src/messages.generated.ts (runtime)
 * - src/messages.encode.jsonc → src/messages.encode.generated.ts (encode)
 * (Vite/TS cannot import JSONC directly.)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const KEY_RE = /^[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9]+)+$/;

/** Strip // and /* *\/ comments outside of strings (JSONC subset). */
export function stripJsonc(input) {
  let out = "";
  let i = 0;
  let inString = false;
  let escape = false;
  while (i < input.length) {
    const c = input[i];
    const next = input[i + 1];
    if (inString) {
      out += c;
      if (escape) {
        escape = false;
      } else if (c === "\\") {
        escape = true;
      } else if (c === '"') {
        inString = false;
      }
      i++;
      continue;
    }
    if (c === '"') {
      inString = true;
      out += c;
      i++;
      continue;
    }
    if (c === "/" && next === "/") {
      i += 2;
      while (i < input.length && input[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && next === "*") {
      i += 2;
      while (i + 1 < input.length && !(input[i] === "*" && input[i + 1] === "/")) {
        i++;
      }
      i += 2;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

/**
 * @param {string} srcName
 * @param {string} outName
 * @param {string} exportName
 * @param {string} typeName
 */
function compileOne(srcName, outName, exportName, typeName) {
  const srcPath = join(pkgRoot, "src", srcName);
  const outPath = join(pkgRoot, "src", outName);
  const raw = readFileSync(srcPath, "utf8");
  let parsed;
  try {
    parsed = JSON.parse(stripJsonc(raw));
  } catch (error) {
    console.error(`[compile-messages] Failed to parse ${srcPath}`);
    throw error;
  }

  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error(`[compile-messages] Catalog must be a non-null object: ${srcName}`);
  }

  /** @type {Record<string, string>} */
  const catalog = {};
  for (const [key, value] of Object.entries(parsed)) {
    if (!KEY_RE.test(key)) {
      throw new Error(`[compile-messages] Invalid message key: ${JSON.stringify(key)}`);
    }
    if (typeof value !== "string" || value.length === 0) {
      throw new Error(
        `[compile-messages] Message value must be a non-empty string: ${key}`,
      );
    }
    catalog[key] = value;
  }

  const keys = Object.keys(catalog).sort();
  const body = keys
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(catalog[key])},`)
    .join("\n");

  const file = `/* Generated by scripts/compile-messages.mjs — do not edit. */
export const ${exportName} = {
${body}
} as const;

export type ${typeName} = keyof typeof ${exportName};
`;

  writeFileSync(outPath, file, "utf8");
  console.log(
    `[compile-messages] Wrote ${keys.length} messages → src/${outName}`,
  );
  return new Set(keys);
}

function main() {
  const runtimeKeys = compileOne(
    "messages.jsonc",
    "messages.generated.ts",
    "MESSAGES",
    "MessageKey",
  );
  const encodeKeys = compileOne(
    "messages.encode.jsonc",
    "messages.encode.generated.ts",
    "ENCODE_MESSAGES",
    "EncodeMessageKey",
  );

  const overlap = [...runtimeKeys].filter((k) => encodeKeys.has(k));
  if (overlap.length > 0) {
    throw new Error(
      `[compile-messages] Duplicate keys across catalogs: ${overlap.join(", ")}`,
    );
  }
}

main();
